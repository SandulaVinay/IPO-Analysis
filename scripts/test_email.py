"""Send an explicitly labelled SMTP connectivity test email.

This script must never fabricate company names or financial metrics. It is a
transport/template smoke test only; production result alerts are generated by
src.results.monitor from official exchange filings.
"""
import asyncio
import sys
from datetime import datetime, timezone

from src.common.config import settings
from src.notifications.email import EmailProvider


async def main() -> int:
    if not settings.email_to:
        print("ERROR: EMAIL_TO is not configured; refusing to send.")
        return 2
    if settings.app_env == "production" and settings.email_provider != "smtp":
        print("ERROR: production email testing requires EMAIL_PROVIDER=smtp")
        return 2
    if not settings.enable_email:
        print("ERROR: email delivery is disabled; refusing to send.")
        return 2

    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    subject = "[IPO Analysis] SMTP connectivity test — NOT a financial-results alert"
    body = (
        "This is an SMTP connectivity test for the IPO Analysis application.\n\n"
        "It does not represent a listed company, exchange announcement, or financial filing.\n"
        "No company metrics, performance interpretation, or investment conclusion is included.\n\n"
        f"Test timestamp: {timestamp}\n"
        "Purpose: verify that the configured email transport accepts a message.\n\n"
        "Real financial-results alerts are sent separately only when the results monitor "
        "identifies an eligible official exchange filing.\n"
    )

    result = await EmailProvider().send_notification(
        recipient=settings.email_to,
        subject=subject,
        content=body,
        metadata={"html_body": None},
    )
    print(f"TEST_SUBJECT={subject}")
    print(f"ACCEPTED={result.get('accepted', False)}")
    print(f"DELIVERED={result.get('delivered', False)}")
    print(f"MOCKED={result.get('mocked', False)}")
    if result.get("error"):
        print(f"ERROR={result['error']}")
    return 0 if result.get("accepted", False) or result.get("delivered", False) else 1


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))

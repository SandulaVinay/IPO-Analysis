"""End-to-end parser tests using a SYNTHETIC prospectus-layout PDF.

This fixture is generated by scripts/generate_official_rhp_fixture.py and is NOT
an official Clean Science filing. Live official-source validation is implemented
separately in scripts/validate_official_esds_drhp.py and its GitHub Actions workflow.
"""
import json
